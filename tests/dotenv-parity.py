"""python-dotenv parity cases for tests/dotenv-test.lisp (cl-stack-config#8).

    uv run --isolated --no-project --with python-dotenv==1.1.1 \
        python -I tests/dotenv-parity.py > tests/dotenv-parity.sexp

With `--random N [SEED]` it writes N cases from another seed, for a local
stress run:

    uv run --isolated --no-project --with python-dotenv==1.1.1 \
        python -I tests/dotenv-parity.py --random 20000 7 > /tmp/dotenv.sexp
    CL_STACK_CONFIG_DOTENV_PARITY=/tmp/dotenv.sexp cl-repo test

Each case is random .env text built from tokens that stress the grammar:
LF, CR and CRLF line ends, Python's Unicode blanks (NBSP, VT, FF, U+001C,
NEL, U+2028, U+3000), quotes, backslashes, comments, export and ${...}.
The expected value is dotenv_values(stream=io.StringIO(text)) with the
process environment set to OUTER=outer, A=envA. Text and values are lists
of character codes, so a CRLF checkout cannot change them; a value is
(:s CODES...) and None is nil, so "" and None stay apart. Texts that hit
a documented difference (README) are left out: a single-quoted value with
${ (expanded by python-dotenv), = followed by blanks and # (python-dotenv:
the # is the value) and a quote after two backslashes. Each line is

  (:case EXPAND (TEXT-CODES) ((NAME-CODES (:s VALUE-CODES...) or nil) ...))
"""
import io
import logging
import os
import random
import re
import sys

import dotenv
from dotenv import dotenv_values

logging.disable(logging.CRITICAL)
os.environ.clear()
os.environ.update({"OUTER": "outer", "A": "envA"})

BLANKS = [" ", "\t", "\xa0", "\x0b", "\x0c", "\x1c", "\x85", " ", "　"]
ENDS = ["\n", "\r", "\r\n"]
KEYS = ["A", "B", "N", "export", "'Q K'", "A.B", "x\xa0y"]
VALUES = ["x", "y z", "'s'", '"d"', "'a\\'b'", '"t\\tn\\nq\\"e"', "${A}", "${N:-d}",
          "${OUTER}", "${M:-z}", "$A", "#h", "a#b", "﻿", "é", '"\\"', "'\\'",
          '"multi\nline"', "'cr\rline'", "\\", '"', "'", "="]
TOKENS = (["A", "B", "N", "x", "=", "#", "'", '"', "\\", "export", "${A}", "${N:-d}",
           "﻿", "é"] + BLANKS + ENDS)


def statement(rng):
    parts = []
    if rng.random() < 0.15:
        parts.append("export" + rng.choice(BLANKS[:3]))
    parts.append(rng.choice(KEYS))
    if rng.random() < 0.3:
        parts.append(rng.choice(BLANKS))
    if rng.random() < 0.85:
        parts.append("=")
        if rng.random() < 0.3:
            parts.append(rng.choice(BLANKS))
        parts.append(rng.choice(VALUES))
        if rng.random() < 0.3:
            parts.append(rng.choice(BLANKS))
    if rng.random() < 0.25:
        parts.append(rng.choice(BLANKS) + "# c")
    return "".join(parts)


def text_case(rng):
    if rng.random() < 0.6:
        out = []
        for _ in range(rng.randint(1, 5)):
            if rng.random() < 0.15:
                out.append(rng.choice(BLANKS + ["# comment"]))
            else:
                out.append(statement(rng))
            out.append(rng.choice(ENDS))
        if rng.random() < 0.3:
            out.pop()
        return "".join(out)
    return "".join(rng.choice(TOKENS) for _ in range(rng.randint(1, 30)))


def documented_difference(text, expand):
    if expand and re.search(r"'[^']*\$\{", text):
        return True
    if re.search(r"=[^\S\r\n]+#", text):
        return True
    return re.search(r"\\\\['\"]", text) is not None


def codes(s):
    return "(" + " ".join(str(ord(c)) for c in s) + ")"


def cases(n, seed):
    rng = random.Random(seed)
    made = 0
    while made < n:
        text = text_case(rng)
        expand = rng.random() < 0.5
        if documented_difference(text, expand):
            continue
        values = dotenv_values(stream=io.StringIO(text), interpolate=expand)
        pairs = " ".join(f"({codes(k)} {'nil' if v is None else '(:s ' + codes(v)[1:]})"
                         for k, v in values.items())
        print(f"(:case {'t' if expand else 'nil'} {codes(text)} ({pairs}))")
        made += 1


if __name__ == "__main__":
    print(f";;; Generated by tests/dotenv-parity.py with python-dotenv "
          f"{dotenv.__version__ if hasattr(dotenv, '__version__') else '1.1.1'}; do not edit.")
    if len(sys.argv) > 1 and sys.argv[1] == "--random":
        cases(int(sys.argv[2]), int(sys.argv[3]) if len(sys.argv) > 3 else 1)
    else:
        cases(600, 8)
